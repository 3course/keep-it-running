const f = (n: number) => Math.round(n * 10) / 10;

/** SVG path data for `str` with its top-left at (x, y), letters `cap` mm tall. Spaces are a letter wide. */
export function text(str: string, x: number, y: number, cap: number): string {
  const k = cap / 10, adv = 8.2 * k;
  let d = '', cx = x;
  for (const ch of str.toUpperCase()) {
    for (const line of G[ch] ?? []) {
      for (let i = 0; i < line.length; i += 2) d += `${i ? 'L' : 'M'}${f(cx + line[i] * k)} ${f(y + line[i + 1] * k)} `;
    }
    cx += ch === ' ' ? adv * 0.7 : ch === '.' || ch === "'" ? adv * 0.6 : adv;
  }
  return d.trim();
}

/** How wide text() draws `str` at `cap` (to centre it). */
export function textWidth(str: string, cap: number): number {
  const adv = 8.2 * cap / 10;
  let w = 0;
  for (const ch of str) w += ch === ' ' ? adv * 0.7 : ch === '.' || ch === "'" ? adv * 0.6 : adv;
  return w - 2.2 * cap / 10;
}

/** Centred on cx. */
export const textC = (str: string, cx: number, y: number, cap: number) => text(str, cx - textWidth(str, cap) / 2, y, cap);
